"""Benchmark: detector precision/recall/F1 vs injected labels, plus throughput."""

from __future__ import annotations

import os
import platform
import statistics
import tempfile
import time
from pathlib import Path
from typing import Any

from sklearn.metrics import roc_auc_score

from agentlens.analyzer import analyze_file, analyze_runs
from agentlens.detectors import DETECTORS
from agentlens.generator import GeneratorConfig, generate, write_dataset
from agentlens.parser import group_runs, parse_span
from agentlens.pricing import PriceTable


def prf(predicted: set[str], actual: set[str]) -> dict[str, float | int]:
    tp = len(predicted & actual)
    fp = len(predicted - actual)
    fn = len(actual - predicted)
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "support": len(actual),
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
    }


def evaluate_detection(n_runs: int = 1000, seed: int = 42) -> dict[str, Any]:
    records, labels = generate(GeneratorConfig(n_runs=n_runs, seed=seed))
    runs = group_runs(parse_span(r) for r in records)
    result = analyze_runs(runs, prices=PriceTable.default_table())
    out: dict[str, Any] = {"n_runs": len(runs), "n_spans": len(records), "seed": seed}
    per: dict[str, Any] = {}
    for det in DETECTORS:
        predicted = {f.trace_id for f in result.findings if f.detector == det.name}
        actual = {t for t, labs in labels.items() if det.name in labs}
        per[det.name] = prf(predicted, actual)
    out["detectors"] = per
    any_actual = {t for t, labs in labels.items() if labs}
    any_pred = {f.trace_id for f in result.findings}
    out["rules_any"] = prf(any_pred, any_actual)
    df = result.run_df
    iso_pred = set(df.loc[df["anomaly_outlier"], "trace_id"])
    out["isolation_forest"] = prf(iso_pred, any_actual)
    y_true = df["trace_id"].isin(any_actual).astype(int)
    out["isolation_forest"]["roc_auc"] = round(float(roc_auc_score(y_true, df["anomaly_score"])), 4)
    out["anomalous_runs"] = len(any_actual)
    return out


def measure_throughput(n_runs: int = 5000, seed: int = 7, repeats: int = 3) -> dict[str, Any]:
    """Time the full file pipeline (parse + metrics + detectors + IsolationForest)."""
    records, labels = generate(GeneratorConfig(n_runs=n_runs, seed=seed))
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "traces.jsonl"
        write_dataset(records, labels, path)
        timings = []
        timings_rules = []
        for _ in range(repeats):
            t0 = time.perf_counter()
            analyze_file(path)
            timings.append(time.perf_counter() - t0)
            t0 = time.perf_counter()
            analyze_file(path, anomaly=False)
            timings_rules.append(time.perf_counter() - t0)
    best = statistics.median(timings)
    best_rules = statistics.median(timings_rules)
    return {
        "n_runs": n_runs,
        "n_spans": len(records),
        "repeats": repeats,
        "median_seconds_full": round(best, 3),
        "spans_per_sec_full": round(len(records) / best),
        "median_seconds_rules_only": round(best_rules, 3),
        "spans_per_sec_rules_only": round(len(records) / best_rules),
        "machine": {
            "python": platform.python_version(),
            "platform": platform.platform(terse=True),
            "cpu_count": os.cpu_count(),
        },
    }


def run_benchmark(
    n_runs: int = 1000,
    seed: int = 42,
    robustness_seeds: tuple[int, ...] = (1, 2, 3, 4, 5),
    throughput_runs: int = 5000,
) -> dict[str, Any]:
    main = evaluate_detection(n_runs=n_runs, seed=seed)
    robustness: dict[str, Any] = {}
    if robustness_seeds:
        per_seed = [evaluate_detection(n_runs=n_runs, seed=s) for s in robustness_seeds]
        for det in DETECTORS:
            f1s = [r["detectors"][det.name]["f1"] for r in per_seed]
            robustness[det.name] = {
                "f1_mean": round(statistics.mean(f1s), 4),
                "f1_std": round(statistics.pstdev(f1s), 4),
            }
        robustness["seeds"] = list(robustness_seeds)
    throughput = measure_throughput(n_runs=throughput_runs) if throughput_runs else {}
    return {"detection": main, "robustness": robustness, "throughput": throughput}


def to_markdown(results: dict[str, Any]) -> str:
    det = results["detection"]
    lines = [
        "# agentlens benchmark results",
        "",
        f"Synthetic dataset: {det['n_runs']} runs / {det['n_spans']} spans, seed {det['seed']}, "
        f"{det['anomalous_runs']} runs with injected anomalies. Generated by `agentlens eval`.",
        "",
        "## Detector accuracy (run level, vs injected labels)",
        "",
        "| Detector | Support | TP | FP | FN | Precision | Recall | F1 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    rows = [
        *det["detectors"].items(),
        ("rules: any detector", det["rules_any"]),
        ("IsolationForest (any anomaly)", det["isolation_forest"]),
    ]
    for name, m in rows:
        lines.append(
            f"| {name} | {m['support']} | {m['tp']} | {m['fp']} | {m['fn']} | "
            f"{m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} |"
        )
    lines.append("")
    lines.append(f"IsolationForest ROC-AUC (any anomaly): {det['isolation_forest']['roc_auc']:.3f}")
    rob = results.get("robustness") or {}
    if rob:
        lines += [
            "",
            f"## F1 robustness across seeds {rob['seeds']}",
            "",
            "| Detector | mean F1 | std |",
            "|---|---:|---:|",
        ]
        for d in DETECTORS:
            lines.append(
                f"| {d.name} | {rob[d.name]['f1_mean']:.3f} | {rob[d.name]['f1_std']:.3f} |"
            )
    tp = results.get("throughput") or {}
    if tp:
        m = tp["machine"]
        lines += [
            "",
            "## Throughput",
            "",
            f"{tp['n_spans']} spans ({tp['n_runs']} runs), median of {tp['repeats']} runs, "
            f"Python {m['python']} on {m['platform']} ({m['cpu_count']} CPUs).",
            "",
            "| Pipeline | Seconds | Spans/sec |",
            "|---|---:|---:|",
            f"| parse + metrics + detectors + IsolationForest | {tp['median_seconds_full']} | "
            f"{tp['spans_per_sec_full']:,} |",
            f"| parse + metrics + detectors | {tp['median_seconds_rules_only']} | "
            f"{tp['spans_per_sec_rules_only']:,} |",
        ]
    return "\n".join(lines) + "\n"
